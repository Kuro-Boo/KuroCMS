-- サイトの時計（IANA タイムゾーン名。例: 'Asia/Tokyo'）。
--
-- ⚠ これが無かった間、公開側は 2 つの時計で動いていた:
--   * 月アーカイブの区切り  … SQLite の strftime = UTC
--   * 記事カードの日付表示  … ブラウザ hydration = 閲覧者のローカル TZ
-- publish_at は保存時に UTC(...Z) へ潰されるので、JST 00:00〜08:59 に公開した
-- 記事は UTC では前月に落ちる。結果「8 月アーカイブに 9/1 の記事が出る」。
-- この列で月の区切りと日付表示の両方を 1 つの時計に寄せる。
--
-- 既定は ''（= UTC）。既存インストールの見た目を勝手に動かさないため、
-- 移行では値を入れない —— 設定画面で選ぶと全ページの再ビルドで反映される。
--
-- restore: 不要 — 列を足すだけでデータを触らない。既定値 '' は復元で流し込む
-- 側の行にそのまま入っており、利用者が選んだ値はバックアップに含まれて戻る。
ALTER TABLE site_settings ADD COLUMN site_timezone TEXT NOT NULL DEFAULT '';
